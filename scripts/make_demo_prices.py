"""Write site/data/demo-prices.json: INVENTED month-end prices for six fictional funds, seeded so the file is reproducible.

These are not real prices and say nothing about any real fund. They exist so the page works offline and can be
published without any question about price-data licensing (issue 57). Run: python scripts/make_demo_prices.py
"""
import json
import random
from datetime import date
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "site" / "data" / "demo-prices.json"
MONTHS = 73  # six years of month-ends: 72 monthly returns, enough for any window up to 5 years plus a margin
# name, label, yearly drift, yearly volatility, sensitivity to the shared "market" factor
FUNDS = [
    ("DEMOUS", "Demo US stocks (broad)", 0.10, 0.16, 1.00),
    ("DEMOSM", "Demo small companies", 0.09, 0.22, 0.95),
    ("DEMOIN", "Demo international stocks", 0.06, 0.17, 0.80),
    ("DEMOBD", "Demo bonds", 0.03, 0.05, 0.10),
    ("DEMOGD", "Demo gold", 0.07, 0.15, 0.05),
    ("DEMOTB", "Demo cash (T-bill-like)", 0.035, 0.002, 0.00),
]


def month_ends(n: int) -> list[date]:
    out, y, m = [], 2020, 9
    for _ in range(n):
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
        nxt = date(y + (m == 12), m % 12 + 1, 1)
        out.append(date.fromordinal(nxt.toordinal() - 1))
    return out


def main() -> None:
    rng = random.Random(20261112)
    market = [rng.gauss(0, 1) for _ in range(MONTHS)]
    series = {}
    for i, (sym, _label, drift, vol, beta) in enumerate(FUNDS):
        own = random.Random(100 + i)
        px, vals = 100.0, []
        for k in range(MONTHS):
            vals.append(round(px, 4))
            shock = beta * market[k] + (1 - beta**2) ** 0.5 * own.gauss(0, 1) if beta < 1 else market[k]
            px *= 1 + drift / 12 + vol / 12**0.5 * shock
        series[sym] = vals
    doc = {
        "note": "INVENTED data. Not real prices. Generated by scripts/make_demo_prices.py.",
        "dates": [d.isoformat() for d in month_ends(MONTHS)],
        "labels": {s: label for s, label, *_ in FUNDS},
        "series": series,
        "rf": 3.5,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"wrote {OUT} ({MONTHS} months, {len(FUNDS)} funds)")


if __name__ == "__main__":
    main()
